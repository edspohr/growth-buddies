#!/usr/bin/env node
/**
 * Regenerates sitemap.xml from the public/ build.
 * Skips noindex pages, 404 and redirect sources.
 *
 * Usage: npm run build && node scripts/generate-sitemap.js
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const PUBLIC = path.join(ROOT, "public");
const SITE = "https://growthbuddies.cl";
const { redirects } = JSON.parse(fs.readFileSync(path.join(ROOT, "firebase.json"), "utf8")).hosting;
const redirected = new Set(redirects.map((redirect) => redirect.source));
const TOP = ["/expense-buddy", "/docflow-buddy", "/agent-buddy", "/diagnostico"];

function priority(route) {
  if (route === "/") return "1.0";
  if (TOP.includes(route)) return "0.9";
  return route.split("/").length === 2 ? "0.8" : "0.6";
}

const routes = fs
  .readdirSync(PUBLIC, { recursive: true })
  .filter((file) => file.endsWith(".html"))
  .filter((file) => !/<meta[^>]+noindex/i.test(fs.readFileSync(path.join(PUBLIC, file), "utf8")))
  .map((file) => "/" + file.replace(/(^|\/)index\.html$/, "").replace(/\.html$/, ""))
  .map((route) => (route.length > 1 ? route.replace(/\/$/, "") : route))
  .filter((route) => route !== "/404" && !redirected.has(route))
  .sort((a, b) => priority(b) - priority(a) || a.localeCompare(b));

const urls = routes
  .map((route) => `  <url>\n    <loc>${SITE}${route === "/" ? "/" : route}</loc>\n    <priority>${priority(route)}</priority>\n  </url>`)
  .join("\n");

fs.writeFileSync(
  path.join(ROOT, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by scripts/generate-sitemap.js; do not edit by hand. -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`
);
console.log(`sitemap.xml: ${routes.length} URLs`);
